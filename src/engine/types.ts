/**
 * Базовые типы движка.
 *
 * Данные ролика (текст, слайды, реплики, правки объектов) живут в
 * `src/decks/<id>/deck.json` — их пишет редактор. Код сцен (`SceneDef`) лежит
 * рядом и отвечает только за рисование.
 */

// ------------------------------------------------------------------ данные

export interface Cue {
  /** Уникальный внутри слайда id, по нему сцена достаёт тайминг. */
  id: string;
  /** Текст закадровой озвучки. Длительность реплики считается из него. */
  say: string;
  /** Короткий текст на экране (если не задан — берётся `say`). */
  show?: string;
  /** Дополнительная пауза после реплики, сек. */
  hold?: number;
  /** Множитель темпа: 0.9 — быстрее, 1.3 — медленнее. */
  rate?: number;
  /**
   * Ручная длительность, сек (до подгонки под хронометраж). Если задана,
   * заменяет расчёт из текста — её ставит редактор при перетаскивании границ.
   */
  dur?: number;
}

/** Правка объекта сцены из редактора. Не задано — берётся значение из кода. */
export interface ObjOverride {
  x?: number;
  y?: number;
  scale?: number;
  text?: string;
  hidden?: boolean;
}

export interface SlideData {
  /** Стабильный id: по нему слайд связывается с кодом сцены. */
  id: string;
  label: string;
  cues: Cue[];
  /** Пауза перед первой репликой, сек. */
  lead?: number;
  /** Пауза после последней реплики, сек. */
  tail?: number;
  /** Правки объектов: id объекта → положение, масштаб, текст. */
  objects?: Record<string, ObjOverride>;
}

export interface DeckFormat {
  /** Высота кадра, px (кадр всегда 16:9). */
  height: number;
  fps: number;
  /** Битрейт, Мбит/с. */
  bitrate: number;
}

/** Звуковая дорожка с голосом. Файл лежит в папке ролика, его кладёт редактор. */
export interface DeckAudio {
  /** Имя файла в `src/decks/<id>/`, например `voice.mp3`. */
  file: string;
  /** С какой секунды ролика звучит начало дорожки (меньше 0 — начало дорожки срезано). */
  offset?: number;
  /** Громкость 0..1, по умолчанию 1. */
  volume?: number;
}

export interface DeckData {
  id: string;
  title: string;
  /** Исходный текст озвучки целиком — из него делалась разбивка. */
  text: string;
  /**
   * Целевой хронометраж, сек. Расписание целиком подгоняется под него;
   * `null` — длина считается из текста при темпе речи из TIMING.
   */
  target: number | null;
  /** Паузы по умолчанию для слайдов ролика (иначе — из TIMING). */
  lead?: number;
  tail?: number;
  format: DeckFormat;
  slides: SlideData[];
  /** Озвучка: играет в редакторе и попадает в MP4. */
  audio?: DeckAudio;
  /** Пресет стиля (`engine/styles.ts`): палитра, шрифты, фон. Нет — Terevo. */
  style?: string;
}

// ------------------------------------------------------------------ рендер

/** Тайминг реплики, посчитанный движком (локально внутри слайда). */
export interface CueTime {
  id: string;
  say: string;
  show: string;
  /** Начало относительно старта слайда, сек. */
  start: number;
  end: number;
  dur: number;
  /** Локальное время внутри реплики (может быть отрицательным до старта). */
  t: number;
  /** Прогресс 0..1. */
  p: number;
  /** Реплика звучит прямо сейчас. */
  on: boolean;
  /** Реплика уже началась. */
  began: boolean;
  /** Реплика уже закончилась. */
  done: boolean;
}

export interface ObjOpts {
  /** Опорная точка объекта в координатах сцены: её двигает редактор, вокруг неё масштаб. */
  x: number;
  y: number;
  /** Текст объекта. Редактор может его заменить — рисовать нужно `o.text`. */
  text?: string;
  /** Подпись в списке объектов редактора. */
  label?: string;
  /**
   * `true` — код внутри рисует в абсолютных координатах сцены (удобно для
   * сложных групп). По умолчанию начало координат внутри — опорная точка.
   */
  abs?: boolean;
}

/** Итоговое состояние объекта с учётом правок редактора. */
export interface ObjState {
  x: number;
  y: number;
  scale: number;
  text: string;
}

/** Код сцены: только рисование. Текст и тайминги приходят из deck.json. */
export interface SceneDef {
  /** id слайда, который рисует эта сцена. */
  id: string;
  render(f: Frame): void;
  /**
   * Насколько «горячий» момент сцены (0..1) — фон реагирует свечением.
   * Чистая функция локального времени, поэтому перемотка выглядит одинаково.
   */
  energy?(t: number, cue: (id: string) => CueTime): number;
}

export interface Frame {
  ctx: CanvasRenderingContext2D;
  /** Локальное время слайда, сек. */
  t: number;
  /** Полная длительность слайда, сек. */
  dur: number;
  /** Глобальное время презентации, сек. */
  gt: number;
  /** Индекс слайда. */
  index: number;
  /** Тайминг реплики по id. Если реплики нет — «пустая», которая никогда не начнётся. */
  cue(id: string): CueTime;
  /** Все реплики слайда по порядку. */
  cues: CueTime[];
  /**
   * Объект сцены — группа рисования, которую редактор умеет выделять,
   * двигать, масштабировать и у которой может править текст.
   */
  obj(id: string, o: ObjOpts, draw: (o: ObjState) => void): void;
}
